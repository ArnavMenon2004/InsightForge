"""
Export tools for converting a FinalReport to downloadable formats.

Supports:
- Markdown (.md)  — zero dependencies, always available.
- PDF (.pdf)      — requires ``reportlab``; degrades gracefully to Markdown
                    if the library is not installed.
"""

from __future__ import annotations

import io
import textwrap
from datetime import datetime

from schemas.report import FinalReport
from utils.logger import logger


class MarkdownExporter:
    """
    Serialise a ``FinalReport`` to a UTF-8 encoded Markdown byte string.

    Appends a references section listing all cited sources so the
    exported file is self-contained.
    """

    def export(self, report: FinalReport, document) -> bytes:
        """
        Build the full Markdown document.

        Args:
            report:   The completed ``FinalReport``.
            document: The ``ResearchDocument`` used to build the report
                      (provides the full source list for the references
                      section).

        Returns:
            UTF-8 encoded bytes ready to pass to ``st.download_button``.
        """
        lines: list[str] = []

        # Header block
        lines.append(f"# {report.title}\n")
        lines.append(
            f"*Generated by InsightForge on "
            f"{datetime.now().strftime('%Y-%m-%d %H:%M')} UTC*\n"
        )
        lines.append("---\n")

        # Executive summary
        lines.append("## Executive Summary\n")
        lines.append(f"{report.executive_summary}\n")
        lines.append("---\n")

        # Main body
        lines.append(report.markdown)
        lines.append("\n")

        # Fact-check summary
        if report.fact_check:
            lines.append("---\n")
            lines.append("## Fact-Check Summary\n")
            lines.append(
                f"**Overall confidence:** {report.fact_check.overall_confidence}\n"
            )
            for fc in report.fact_check.results:
                lines.append(f"\n**{fc.verdict}** — {fc.claim}\n")
                lines.append(f"_{fc.explanation}_\n")

        # References
        seen: set[str] = set()
        all_sources = []
        for section in document.sections:
            for src in section.sources:
                key = str(src.url)
                if key not in seen:
                    seen.add(key)
                    all_sources.append(src)

        if all_sources:
            lines.append("\n---\n")
            lines.append("## References\n")
            for i, src in enumerate(all_sources, start=1):
                lines.append(f"{i}. [{src.title}]({src.url})\n")

        return "\n".join(lines).encode("utf-8")


class PDFExporter:
    """
    Serialise a ``FinalReport`` to a PDF byte string using ``reportlab``.

    Falls back to ``MarkdownExporter`` and raises ``ImportError`` if
    ``reportlab`` is not installed, so the caller can handle the
    degradation gracefully.
    """

    def export(self, report: FinalReport, document) -> bytes:
        """
        Build the PDF document.

        Args:
            report:   The completed ``FinalReport``.
            document: The ``ResearchDocument`` (for references).

        Returns:
            Raw PDF bytes.

        Raises:
            ImportError: If ``reportlab`` is not installed.
        """
        try:
            from reportlab.lib.pagesizes import A4
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.lib.units import cm
            from reportlab.lib import colors
            from reportlab.platypus import (
                SimpleDocTemplate,
                Paragraph,
                Spacer,
                HRFlowable,
            )
        except ImportError:
            logger.warning(
                "reportlab is not installed — PDF export unavailable. "
                "Install it with: pip install reportlab"
            )
            raise

        buffer = io.BytesIO()

        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=2.5 * cm,
            rightMargin=2.5 * cm,
            topMargin=2.5 * cm,
            bottomMargin=2.5 * cm,
        )

        styles = getSampleStyleSheet()

        # Custom style overrides
        title_style = ParagraphStyle(
            "InsightTitle",
            parent=styles["Title"],
            fontSize=20,
            textColor=colors.HexColor("#1a1a2e"),
            spaceAfter=6,
        )
        h2_style = ParagraphStyle(
            "InsightH2",
            parent=styles["Heading2"],
            fontSize=13,
            textColor=colors.HexColor("#16213e"),
            spaceBefore=14,
            spaceAfter=4,
        )
        body_style = ParagraphStyle(
            "InsightBody",
            parent=styles["Normal"],
            fontSize=10,
            leading=15,
            spaceAfter=8,
        )
        meta_style = ParagraphStyle(
            "InsightMeta",
            parent=styles["Italic"],
            fontSize=9,
            textColor=colors.grey,
            spaceAfter=12,
        )

        story = []

        # Title
        story.append(Paragraph(report.title, title_style))
        story.append(
            Paragraph(
                f"Generated by InsightForge · "
                f"{datetime.now().strftime('%Y-%m-%d %H:%M')} UTC",
                meta_style,
            )
        )
        story.append(HRFlowable(width="100%", thickness=1, color=colors.lightgrey))
        story.append(Spacer(1, 0.3 * cm))

        # Executive summary
        story.append(Paragraph("Executive Summary", h2_style))
        story.append(Paragraph(report.executive_summary, body_style))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.lightgrey))

        # Main body — strip Markdown headings, render paragraphs
        for line in report.markdown.splitlines():
            stripped = line.strip()
            if not stripped:
                story.append(Spacer(1, 0.2 * cm))
            elif stripped.startswith("## "):
                story.append(Paragraph(stripped[3:], h2_style))
            elif stripped.startswith("### "):
                story.append(
                    Paragraph(
                        stripped[4:],
                        ParagraphStyle(
                            "InsightH3",
                            parent=h2_style,
                            fontSize=11,
                            spaceBefore=8,
                        ),
                    )
                )
            elif stripped.startswith("# "):
                pass  # already rendered as title
            elif stripped.startswith("---"):
                story.append(
                    HRFlowable(
                        width="100%", thickness=0.5, color=colors.lightgrey
                    )
                )
            else:
                # Escape XML special chars for reportlab
                safe = (
                    stripped
                    .replace("&", "&amp;")
                    .replace("<", "&lt;")
                    .replace(">", "&gt;")
                )
                story.append(Paragraph(safe, body_style))

        # Fact-check block
        if report.fact_check:
            story.append(
                HRFlowable(width="100%", thickness=0.5, color=colors.lightgrey)
            )
            story.append(Paragraph("Fact-Check Summary", h2_style))
            story.append(
                Paragraph(
                    f"Overall confidence: <b>{report.fact_check.overall_confidence}</b>",
                    body_style,
                )
            )
            for fc in report.fact_check.results:
                verdict_color = {
                    "SUPPORTED": "#2d6a4f",
                    "UNSUPPORTED": "#c1121f",
                    "UNVERIFIABLE": "#e76f51",
                }.get(fc.verdict, "#333333")
                story.append(
                    Paragraph(
                        f'<font color="{verdict_color}"><b>{fc.verdict}</b></font>'
                        f" — {fc.claim}",
                        body_style,
                    )
                )
                story.append(Paragraph(f"<i>{fc.explanation}</i>", body_style))

        # References
        seen: set[str] = set()
        all_sources = []
        for section in document.sections:
            for src in section.sources:
                key = str(src.url)
                if key not in seen:
                    seen.add(key)
                    all_sources.append(src)

        if all_sources:
            story.append(
                HRFlowable(width="100%", thickness=0.5, color=colors.lightgrey)
            )
            story.append(Paragraph("References", h2_style))
            for i, src in enumerate(all_sources, start=1):
                story.append(
                    Paragraph(
                        f"{i}. {src.title} — <i>{src.url}</i>",
                        body_style,
                    )
                )

        doc.build(story)
        return buffer.getvalue()
