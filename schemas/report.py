from pydantic import BaseModel, Field


class CitedClaim(BaseModel):
    """
    A single factual claim extracted from the report, with its
    supporting source index.

    Produced by the CitationAgent.
    """

    claim: str = Field(description="The factual claim as it appears in the report.")

    source_indices: list[int] = Field(
        description=(
            "One-based indices into the ResearchDocument source list that "
            "support this claim."
        )
    )


class FactCheckResult(BaseModel):
    """
    Outcome of the FactCheckerAgent for a single claim.
    """

    claim: str = Field(description="The claim that was checked.")

    verdict: str = Field(
        description=(
            "One of: SUPPORTED, UNSUPPORTED, or UNVERIFIABLE.  "
            "SUPPORTED means the claim is directly backed by the sources.  "
            "UNSUPPORTED means the sources contradict it.  "
            "UNVERIFIABLE means the sources do not contain enough information."
        )
    )

    explanation: str = Field(
        description="Brief explanation of the verdict (one to two sentences)."
    )


class FactCheckReport(BaseModel):
    """
    Complete fact-check output produced by the FactCheckerAgent.

    Contains one FactCheckResult per claim identified in the draft.
    """

    results: list[FactCheckResult] = Field(
        description="Fact-check results for every claim examined."
    )

    overall_confidence: str = Field(
        description=(
            "High, Medium, or Low — overall confidence in the report's "
            "factual accuracy based on the proportion of supported claims."
        )
    )


class FinalReport(BaseModel):
    """
    Complete output produced by the full InsightForge pipeline.

    Fields
    ------
    title        : Report title generated by the WriterAgent.
    executive_summary : One-paragraph overview for quick consumption.
    markdown     : Full report body in GitHub-flavoured Markdown.
    fact_check   : FactCheckReport attached by the FactCheckerAgent.
    citations    : Inline citation map attached by the CitationAgent.
    """

    title: str = Field(description="Report title.")

    executive_summary: str = Field(
        description="One concise paragraph summarising the entire report."
    )

    markdown: str = Field(
        description="Full report body in GitHub-flavoured Markdown."
    )

    fact_check: FactCheckReport | None = Field(
        default=None,
        description="Fact-check results; None until FactCheckerAgent runs.",
    )

    citations: list[CitedClaim] | None = Field(
        default=None,
        description="Citation map; None until CitationAgent runs.",
    )
